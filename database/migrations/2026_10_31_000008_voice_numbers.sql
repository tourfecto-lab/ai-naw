-- TOURFECTO AI VOICE & SALES AGENT (Phase 3): phone numbers and purchase orders. Additive only.
CREATE TABLE IF NOT EXISTS voice_numbers (
 id INT(11) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_user_id INT(11) NOT NULL,
 e164 VARCHAR(20) NOT NULL,
 country CHAR(2) NULL,
 number_type VARCHAR(20) NOT NULL DEFAULT 'local',
 source ENUM('purchased','connected') NOT NULL,
 connect_method VARCHAR(20) NULL COMMENT 'provider_native | forward | sip | port',
 provider VARCHAR(30) NULL,
 provider_number_id VARCHAR(80) NULL,
 status ENUM('simulated','pending','pending_verification','verified','awaiting_link_test','port_requested','active','failed') NOT NULL DEFAULT 'pending',
 verification_mode ENUM('none','live','sandbox') NOT NULL DEFAULT 'none' COMMENT 'sandbox proof can never enable live use',
 verification_hash CHAR(64) NULL,
 verification_expires_at DATETIME NULL,
 verification_attempts TINYINT NOT NULL DEFAULT 0,
 verified_at DATETIME NULL,
 link_tested_at DATETIME NULL,
 agent_id INT(11) NULL,
 forward_to VARCHAR(20) NULL COMMENT 'human handoff / call forwarding target',
 monthly_cost DECIMAL(10,2) NULL,
 setup_cost DECIMAL(10,2) NULL,
 currency CHAR(3) NULL,
 created_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL,
 live_key VARCHAR(20) NULL COMMENT 'e164 once ownership is proven live (or bought live); unique so nobody can squat a number',
 UNIQUE KEY uq_voice_number_live (live_key),
 KEY idx_voice_number_e164 (e164),
 KEY idx_voice_numbers_tenant (tenant_user_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS voice_number_orders (
 id INT(11) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_user_id INT(11) NOT NULL,
 provider VARCHAR(30) NOT NULL,
 e164 VARCHAR(20) NOT NULL,
 country CHAR(2) NOT NULL,
 number_type VARCHAR(20) NOT NULL,
 monthly_cost DECIMAL(10,2) NOT NULL,
 setup_cost DECIMAL(10,2) NOT NULL DEFAULT 0,
 first_charge DECIMAL(10,2) NOT NULL,
 currency CHAR(3) NOT NULL,
 usage_json TEXT NULL,
 requirement_level VARCHAR(40) NOT NULL,
 needs_ack TINYINT(1) NOT NULL DEFAULT 1,
 status ENUM('quoted','approved','completed','failed','cancelled') NOT NULL DEFAULT 'quoted',
 quoted_by_user_id INT(11) NULL,
 approved_by_user_id INT(11) NULL,
 quoted_at DATETIME NOT NULL,
 approved_at DATETIME NULL,
 result_json TEXT NULL,
 KEY idx_voice_orders_tenant (tenant_user_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
