-- TOURFECTO AI VOICE & SALES AGENT (Phase 4): calls and conversation turns. Additive only.
CREATE TABLE IF NOT EXISTS voice_calls (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_user_id INT(11) NOT NULL,
 number_id INT(11) NULL,
 agent_id INT(11) NULL,
 provider VARCHAR(30) NOT NULL,
 call_sid VARCHAR(80) NOT NULL,
 direction ENUM('inbound','outbound') NOT NULL DEFAULT 'inbound',
 from_e164 VARCHAR(20) NULL,
 to_e164 VARCHAR(20) NULL,
 mode ENUM('turn','stream','fallback') NOT NULL DEFAULT 'turn',
 status ENUM('in_progress','completed','transferred','missed','failed') NOT NULL DEFAULT 'in_progress',
 language VARCHAR(10) NULL,
 after_hours TINYINT(1) NOT NULL DEFAULT 0,
 handoff_topic VARCHAR(20) NULL,
 utm_link_id INT(11) NULL COMMENT 'ad link of the dedicated number that was called (trusted attribution only)',
 attribution_source VARCHAR(30) NULL,
 job_id BIGINT UNSIGNED NULL COMMENT 'outbound job that placed this call',
 answered_by VARCHAR(20) NULL COMMENT 'human / machine / fax / unknown (voicemail detection)',
 contact_id INT(11) NULL,
 identity_verified TINYINT(1) NOT NULL DEFAULT 0,
 verify_attempts TINYINT NOT NULL DEFAULT 0,
 silent_turns TINYINT NOT NULL DEFAULT 0,
 turns INT NOT NULL DEFAULT 0,
 outcome VARCHAR(30) NULL,
 handoff_reason VARCHAR(200) NULL,
 qualification TEXT NULL COMMENT 'JSON collected by the agent (lead qualification)',
 booking_request TEXT NULL COMMENT 'JSON booking request captured on the call (confirmed in Phase 6)',
 summary TEXT NULL,
 next_step VARCHAR(300) NULL,
 needs TEXT NULL COMMENT 'JSON list of customer needs',
 send_requests TEXT NULL COMMENT 'JSON: details / payment link the caller asked to receive',
 post_call_status ENUM('none','pending','done','failed') NOT NULL DEFAULT 'none',
 post_call_attempts TINYINT NOT NULL DEFAULT 0,
 post_processed_at DATETIME NULL,
 crm_lead_id INT(11) NULL,
 booking_id INT(11) NULL,
 ai_cost_usd DECIMAL(10,4) NOT NULL DEFAULT 0,
 latency_ms_total INT NOT NULL DEFAULT 0 COMMENT 'sum of reply times (turn mode)',
 latency_samples INT NOT NULL DEFAULT 0,
 started_at DATETIME NOT NULL,
 ended_at DATETIME NULL,
 duration_s INT NULL,
 UNIQUE KEY uq_voice_call_sid (provider, call_sid),
 KEY idx_voice_calls_tenant (tenant_user_id, started_at),
 KEY idx_voice_calls_contact (tenant_user_id, contact_id),
 KEY idx_voice_calls_post (post_call_status, ended_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS voice_call_turns (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 call_id BIGINT UNSIGNED NOT NULL,
 tenant_user_id INT(11) NOT NULL,
 seq INT NOT NULL,
 role ENUM('caller','agent','tool') NOT NULL,
 text TEXT NOT NULL,
 meta TEXT NULL,
 created_at DATETIME NOT NULL,
 UNIQUE KEY uq_voice_turn (call_id, seq, role),
 KEY idx_voice_turns_call (call_id, seq)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
